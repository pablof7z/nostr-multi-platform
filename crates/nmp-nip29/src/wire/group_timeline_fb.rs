// --- encode ---------------------------------------------------------------

/// Encode a [`GroupTimelineSnapshot`] to typed FlatBuffers bytes (with the `NGTL`
/// file identifier). `events` order is preserved verbatim (newest-first as the
/// projection emits it).
#[must_use]
pub fn encode_group_timeline_snapshot(snapshot: &GroupTimelineSnapshot) -> Vec<u8> {
    let mut fbb = FlatBufferBuilder::new();

    let event_offsets: Vec<WIPOffset<fb::GroupTimelineEvent<'_>>> = snapshot
        .events
        .iter()
        .map(|event| encode_event(&mut fbb, event))
        .collect();
    let events = fbb.create_vector(&event_offsets);

    let root = fb::GroupTimelineSnapshot::create(
        &mut fbb,
        &fb::GroupTimelineSnapshotArgs {
            schema_version: GROUP_TIMELINE_SCHEMA_VERSION,
            events: Some(events),
        },
    );
    fb::finish_group_timeline_snapshot_buffer(&mut fbb, root);
    fbb.finished_data().to_vec()
}

fn encode_event<'a>(
    fbb: &mut FlatBufferBuilder<'a>,
    event: &GroupTimelineEvent,
) -> WIPOffset<fb::GroupTimelineEvent<'a>> {
    let id = fbb.create_string(&event.id);
    let pubkey = fbb.create_string(&event.pubkey);
    let content = fbb.create_string(&event.content);
    fb::GroupTimelineEvent::create(
        fbb,
        &fb::GroupTimelineEventArgs {
            id: Some(id),
            pubkey: Some(pubkey),
            content: Some(content),
            created_at: event.created_at,
            kind: event.kind,
        },
    )
}

// --- decode ---------------------------------------------------------------

/// Decode typed FlatBuffers bytes (as produced by [`encode_group_timeline_snapshot`])
/// back into a [`GroupTimelineSnapshot`]. Returns an error string on any malformed
/// input or missing required field.
pub fn decode_group_timeline_snapshot(bytes: &[u8]) -> Result<GroupTimelineSnapshot, String> {
    if bytes.len() < 8 || !fb::group_timeline_snapshot_buffer_has_identifier(bytes) {
        return Err("missing NGTL file identifier".to_string());
    }
    let root = fb::root_as_group_timeline_snapshot(bytes)
        .map_err(|e| format!("not a valid GroupTimelineSnapshot buffer: {e}"))?;

    let mut events = Vec::new();
    if let Some(fb_events) = root.events() {
        events.reserve(fb_events.len());
        for fb_event in fb_events.iter() {
            events.push(decode_event(fb_event)?);
        }
    }

    Ok(GroupTimelineSnapshot { events })
}

fn decode_event(event: fb::GroupTimelineEvent<'_>) -> Result<GroupTimelineEvent, String> {
    Ok(GroupTimelineEvent {
        id: str_field(event.id(), "GroupTimelineEvent.id")?,
        pubkey: str_field(event.pubkey(), "GroupTimelineEvent.pubkey")?,
        content: str_field(event.content(), "GroupTimelineEvent.content")?,
        created_at: event.created_at(),
        kind: event.kind(),
    })
}

/// Require a present string field; an absent FlatBuffers string on a mandatory
/// slot is a decode error.
fn str_field(value: Option<&str>, ctx: &str) -> Result<String, String> {
    value
        .map(str::to_string)
        .ok_or_else(|| format!("{ctx}: missing required string field"))
}
