//! Typed FlatBuffers wire codec for [`crate::projection::GroupTimelineSnapshot`].
//!
//! The canonical FFI shape is the serde JSON of `GroupTimelineSnapshot`
//! (`GroupTimelineProjection::snapshot_json`). This module adds a **typed
//! FlatBuffers** encoding of the same read model — the typed sidecar (ADR-0037)
//! carried alongside the generic `Value` projection under the same
//! `"nmp.nip29.group_timeline"` key. The serde shape stays authoritative; this is the
//! typed payload a `NGTL`-aware host decodes with generated accessors instead of
//! JSON reflection.
//!
//! Raw data only (ADR-0032): every field is the raw protocol value — hex event
//! ids / pubkeys, verbatim content, Unix-second `created_at`, raw kind. No
//! `display::` forwarder runs on the encode path.
//!
//! Honours D6 (no panics): [`decode_group_timeline_snapshot`] returns `Err(String)`
//! on any malformed input; there are no `unwrap`/`expect`/panicking-index
//! operations on the decode path.
//!
//! ## Regenerating the bindings
//!
//! The checked-in bindings in `wire/generated/group_timeline_generated.rs` are
//! produced by `flatc` from `schema/group_timeline.fbs`. Regenerate only with the
//! workspace FlatBuffers pin (`25.12.19`), enforced by
//! `ci/check-flatbuffers-version-pins.sh`. The schema is self-contained, so
//! generate with plain `flatc --rust`:
//!
//! ```sh
//! flatc --rust -o crates/nmp-nip29/src/wire/generated \
//!       crates/nmp-nip29/schema/group_timeline.fbs
//! ```

