//! Typed FlatBuffers wire codec for [`crate::projection::GroupRosterSnapshot`].
//!
//! The canonical FFI shape is the serde JSON of `GroupRosterSnapshot`
//! (`GroupRosterProjection::snapshot_json`). This module adds a **typed
//! FlatBuffers** encoding of the same read model — the typed sidecar (ADR-0072)
//! carried under the `"nmp.nip29.group_roster"` key. The serde shape stays
//! authoritative; this is the typed payload a `NGRS`-aware host decodes with
//! generated accessors instead of JSON reflection.
//!
//! Raw data only (ADR-0072): every field is the raw protocol value — hex
//! pubkeys and verbatim role tokens. No `display::` forwarder runs on the
//! encode path.
//!
//! Honours D6 (no panics): [`decode_group_roster_snapshot`] returns
//! `Err(String)` on any malformed input; there are no `unwrap`/`expect`/
//! panicking-index operations on the decode path.
//!
//! ## Regenerating the bindings
//!
//! The checked-in bindings in `wire/generated/group_roster_generated.rs` are
//! produced by `flatc` from `schema/group_roster.fbs`. Regenerate only with the
//! workspace FlatBuffers pin (`25.12.19`):
//!
//! ```sh
//! flatc --rust -o crates/nmp-nip29/src/wire/generated \
//!       crates/nmp-nip29/schema/group_roster.fbs
//! ```

