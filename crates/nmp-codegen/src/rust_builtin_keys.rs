//! ADR-0053 / Workstream-E4 — generator for `nmp-core`'s
//! `KERNEL_BUILTIN_PROJECTION_KEYS` const.
//!
//! The kernel built-in projection key set is **derived from the codegen
//! registry**, not hand-maintained. This module renders a tiny `.generated.rs`
//! containing the const from [`kernel_builtin_projection_keys`], which the
//! kernel `include!`s. A drift gate (`nmp gen builtin-keys --check`, run in
//! `.github/workflows/codegen-drift.yml`) fails any PR whose checked-in file
//! differs from a fresh render, and `nmp-core`'s
//! `builtin_projection_keys_const_matches_runtime` test pins the generated const
//! against the kernel's actual `make_update` emission — so the registry, the
//! generated const, and the producer can never silently diverge.
//!
//! Driven entirely by [`crate::swift_projections_registry`]; takes no schema
//! stdin (same shape as [`crate::swift_typed_decoders`]).

use std::path::Path;

use crate::projection_tier::kernel_builtin_projection_keys;

/// Render the `KERNEL_BUILTIN_PROJECTION_KEYS` Rust source from the registry.
///
/// The output is a `pub const &[&str]` of the sorted Tier-2 kernel built-in
/// keys, included by `crates/nmp-core/src/kernel/update/projections.rs`.
#[must_use]
pub fn render_builtin_keys() -> String {
    let keys = kernel_builtin_projection_keys();
    let mut out = String::new();
    out.push_str(
        "// @generated by `cargo run -p nmp-codegen -- gen builtin-keys`. DO NOT EDIT.\n\
         //\n\
         // Source of truth: crates/nmp-codegen/src/swift_projections_registry.rs\n\
         //   (SNAPSHOT_PROJECTIONS entries tagged ProjectionTier::KernelBuiltin, unioned\n\
         //    with KERNEL_BUILTINS_WITHOUT_SHELL_DECODER). Regenerate + verify drift via\n\
         //   `.github/workflows/codegen-drift.yml` (nmp gen builtin-keys --check).\n\
         //\n\
         // The kernel's `builtin_projection_keys_const_matches_runtime` test pins this\n\
         // const against the actual `make_update` emission, so the generated list, the\n\
         // registry, and the producer cannot diverge.\n",
    );
    out.push_str("pub const KERNEL_BUILTIN_PROJECTION_KEYS: &[&str] = &[\n");
    for key in &keys {
        out.push_str(&format!("    {key:?},\n"));
    }
    out.push_str("];\n");
    out
}

/// Outcome of a `--check` run. Mirrors [`crate::swift::SwiftCheckOutcome`].
#[derive(Debug)]
pub struct BuiltinKeysCheckOutcome {
    /// `true` when the on-disk file matches the freshly-rendered output.
    pub up_to_date: bool,
    /// First differing line (1-based) when not up-to-date; `None` when
    /// up-to-date OR when the file doesn't exist.
    pub first_diff_line: Option<usize>,
}

/// Write the generated const Rust to `out_path`, replacing whatever was there.
///
/// # Errors
/// Filesystem I/O failures.
pub fn generate_builtin_keys(out_path: &Path) -> std::io::Result<()> {
    let rendered = render_builtin_keys();
    if let Some(parent) = out_path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(out_path, rendered)
}

/// Diff a freshly-rendered output against the file at `out_path`. A missing
/// file is reported as stale (`up_to_date = false`), matching the other gates.
///
/// # Errors
/// Filesystem I/O failures other than NotFound.
pub fn check_builtin_keys(out_path: &Path) -> std::io::Result<BuiltinKeysCheckOutcome> {
    let rendered = render_builtin_keys();
    let actual = match std::fs::read_to_string(out_path) {
        Ok(s) => s,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            return Ok(BuiltinKeysCheckOutcome {
                up_to_date: false,
                first_diff_line: None,
            });
        }
        Err(err) => return Err(err),
    };
    if actual == rendered {
        return Ok(BuiltinKeysCheckOutcome {
            up_to_date: true,
            first_diff_line: None,
        });
    }
    let first_diff_line = crate::diff_report::first_diff_or_length(&actual, &rendered);
    Ok(BuiltinKeysCheckOutcome {
        up_to_date: false,
        first_diff_line,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_is_stable_and_sorted() {
        let a = render_builtin_keys();
        let b = render_builtin_keys();
        assert_eq!(a, b, "render must be deterministic");
        assert!(a.contains("pub const KERNEL_BUILTIN_PROJECTION_KEYS"));
        // The out-of-registry built-in signed_events is present.
        // ADR-0063 Lane H: mention_profiles removed (kernel no longer emits it).
        assert!(a.contains("\"signed_events\""));
        assert!(!a.contains("\"mention_profiles\""), "mention_profiles must be removed (ADR-0063 Lane H)");
        // A Tier-2 decodable built-in is present.
        assert!(a.contains("\"relay_diagnostics\""));
        // A Tier-1 host registration is NOT a built-in.
        assert!(!a.contains("\"wallet\""));
        // A transient JSON-era key is NOT a built-in.
        assert!(!a.contains("\"timeline\""));
    }
}
