/// Look up an action contract by routing namespace.
#[must_use]
pub fn lookup(namespace: &str) -> Option<&'static ActionContract> {
    ACTION_CONTRACT.iter().find(|c| c.namespace == namespace)
}

/// Look up an action contract by namespace and fail closed when it is missing.
///
/// # Panics
/// When `namespace` has no [`ACTION_CONTRACT`] row.
#[must_use]
pub fn contract_for(namespace: &str) -> &'static ActionContract {
    lookup(namespace).unwrap_or_else(|| {
        panic!(
            "no ActionContract entry for namespace {namespace:?} — every default \
             typed action namespace MUST have an ACTION_CONTRACT row"
        )
    })
}

/// Sorted namespaces for the canonical default composition, including the
/// `nmp-core` built-in publish action. Wallet, zaps, and Marmot namespaces are
/// opt-in/post-v1 and are excluded from this set so the `register_defaults`
/// matching test stays green on default builds.
#[must_use]
pub fn canonical_default_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| {
        c.default_tier != ActionDefaultTier::Wallet
            && c.default_tier != ActionDefaultTier::Marmot
            && c.default_tier != ActionDefaultTier::ComponentRegistered
            && c.default_tier != ActionDefaultTier::Zaps
    })
}

/// Sorted wallet-tier action namespaces (opt-in via `with_wallet`).
#[must_use]
pub fn wallet_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::Wallet)
}

/// Sorted marmot-tier action namespaces (opt-in via `--features marmot`).
#[must_use]
pub fn marmot_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::Marmot)
}

/// Sorted namespaces registered by `nmp_defaults::register_substrate`.
#[must_use]
pub fn substrate_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::Substrate)
}

/// Sorted social-tier action namespaces.
#[must_use]
pub fn social_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::Social)
}

/// Sorted DM-tier action namespaces.
#[must_use]
pub fn dm_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::DirectMessages)
}

/// Sorted zap-tier action namespaces, retained for post-v1/private crate tests
/// but not registered by `nmp-defaults`.
#[must_use]
pub fn zap_action_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| c.default_tier == ActionDefaultTier::Zaps)
}

/// Namespaces with an explicit JSON-only exemption.
#[must_use]
pub fn typed_dispatch_exemption_namespaces() -> Vec<&'static str> {
    sorted_namespaces(|c| matches!(c.typed_dispatch, TypedDispatchPolicy::Exempt { .. }))
}

fn sorted_namespaces(mut pred: impl FnMut(&ActionContract) -> bool) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = ACTION_CONTRACT
        .iter()
        .filter(|c| pred(c))
        .map(|c| c.namespace)
        .collect();
    out.sort_unstable();
    out.dedup();
    out
}

/// Render a compact Markdown report for PR review.
#[must_use]
pub fn render_action_contract_report() -> String {
    let mut rows: Vec<&ActionContract> = ACTION_CONTRACT.iter().collect();
    rows.sort_unstable_by_key(|c| c.namespace);
    let mut out = String::from(
        "| namespace | tier | schema | file id | builder | re-export | producer |\n\
         |---|---|---|---|---|---|---|\n",
    );
    for c in rows {
        out.push_str(&format!(
            "| `{}` | `{:?}` | `{}` v{} | `{}` | `{}` | `{:?}` | {} |\n",
            c.namespace,
            c.default_tier,
            c.schema_id,
            c.schema_version,
            c.file_identifier,
            builder_label(c.builder_support),
            c.public_re_export,
            c.producer
        ));
    }
    out
}

fn builder_label(support: BuilderSupport) -> &'static str {
    match support {
        BuilderSupport::GeneratedFlatTable => "generated:flat",
        BuilderSupport::GeneratedBookmarkItemTable => "generated:bookmark-item",
        BuilderSupport::GeneratedBookmarkSetItemTable => "generated:bookmark-set-item",
        BuilderSupport::GeneratedPublishUnion => "generated:publish-union",
        BuilderSupport::GeneratedMarmotUnion => "generated:marmot-union",
        BuilderSupport::NotGenerated { .. } => "not-generated:tracked",
    }
}

