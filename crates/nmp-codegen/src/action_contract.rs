//! #1939 — neutral typed action contract manifest.
//!
//! This is the action-side twin of [`crate::projection_contract`]: one
//! platform-neutral source for each default typed action's routing namespace,
//! producing crate/module, payload schema id, schema version, FlatBuffers file
//! identifier, default-composition tier, generated-builder posture, public
//! re-export policy, and typed-dispatch exemption state.
//!
//! `nmp-core` stays protocol-neutral: this manifest lives in `nmp-codegen`
//! because it must name NIP namespaces and host-builder facts.

/// Where a default action enters the standard NMP composition.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActionDefaultTier {
    /// Registered by `nmp-core::kernel::default_registry`.
    CoreBuiltin,
    /// Registered by `nmp_defaults::register_substrate`.
    Substrate,
    /// Registered when `NmpDefaults.social` is enabled.
    Social,
    /// Registered when `NmpDefaults.dms` is enabled.
    DirectMessages,
    /// Post-v1 zap action row. Not registered by `nmp-defaults` v1 composition
    /// (#2318).
    Zaps,
    /// Registered opt-in via `NmpAppBuilder::with_wallet` — NOT part of the
    /// default composition. Excluded from [`canonical_default_action_namespaces`]
    /// so `register_defaults` matching tests stay green.
    Wallet,
    /// Registered when the `marmot` feature is on (MLS-over-Nostr seam). NOT
    /// part of the default composition — `nmp-marmot` is a feature-gated dep.
    /// Excluded from [`canonical_default_action_namespaces`] so the no-marmot
    /// contract set-equality test stays green without a dep on `nmp-marmot`.
    Marmot,
    /// Registered by an app-component crate (e.g. `nmp-relations`, `nmp-blossom`)
    /// that is wired in at app-assembly time, not by `nmp-defaults`. Excluded
    /// from [`canonical_default_action_namespaces`] and from the
    /// `contract_matches_modules_and_default_payload_reexports` test so the
    /// no-blossom / no-relations default build stays green.
    ComponentRegistered,
}

/// Whether host action builders are generated for this namespace.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuilderSupport {
    /// Generated by the flat-table `ACTION_BUILDERS` loop.
    GeneratedFlatTable,
    /// Generated by the nested NIP-51 bookmark-item builder path.
    GeneratedBookmarkItemTable,
    /// Generated by the NIP-51 bookmark-set item builder path (like
    /// `GeneratedBookmarkItemTable` but for `BookmarkSetUpdatePayload`, which adds
    /// `set_kind:ubyte` and `identifier:string` fields before the `BookmarkItem`
    /// nested table).
    GeneratedBookmarkSetItemTable,
    /// Generated by the dedicated `nmp.publish` union-body emitters.
    GeneratedPublishUnion,
    /// Generated by the dedicated `nmp.marmot` union-body emitters (M14-1c /
    /// #2169). One namespace, nine arms — same union pattern as publish.
    GeneratedMarmotUnion,
    /// Public typed payload exists, but no generated host builder is emitted.
    NotGenerated {
        /// Tracked rationale for the absence.
        reason: &'static str,
    },
}

/// How `nmp-defaults::action_payloads` exposes the payload type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PublicReExportPolicy {
    /// Re-export the typed payload through `nmp_defaults::action_payloads`.
    DefaultsActionPayloads,
    /// Keep the typed payload in its owning crate; not re-exported by
    /// `nmp-defaults`.
    NotReExported {
        /// Tracked rationale for the absence.
        reason: &'static str,
    },
}

/// Whether a registered default is allowed to be JSON-only.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TypedDispatchPolicy {
    /// Must implement `ActionPayload` and be reachable through the byte doorway.
    TypedOnly,
    /// Explicit tracked exemption. The issue URL must explain the remaining
    /// migration and deadline; the current table intentionally has none.
    Exempt { issue: &'static str },
}

/// One default typed action's neutral public contract.
#[derive(Debug)]
pub struct ActionContract {
    /// Open-registry routing key stamped into `DispatchEnvelope.action_namespace`.
    pub namespace: &'static str,
    /// Crate/module that registers the action module.
    pub producer: &'static str,
    /// Rust `ActionModule` type that owns this namespace.
    pub module_type: &'static str,
    /// Rust `ActionPayload` type decoded for this namespace.
    pub payload_type: &'static str,
    /// Positive ownership claim that owns this action namespace/surface.
    pub owner_claim: &'static str,
    /// Stable payload schema id (`ActionPayload::SCHEMA_ID`).
    pub schema_id: &'static str,
    /// FlatBuffers schema file path, relative to the repo root.
    pub schema_path: &'static str,
    /// FlatBuffers root type.
    pub root_type: &'static str,
    /// Payload schema version (`ActionPayload::SCHEMA_VERSION`).
    pub schema_version: u32,
    /// Four-byte FlatBuffers `file_identifier`.
    pub file_identifier: &'static str,
    /// Default composition tier.
    pub default_tier: ActionDefaultTier,
    /// Generated host-builder posture.
    pub builder_support: BuilderSupport,
    /// Public typed payload re-export posture.
    pub public_re_export: PublicReExportPolicy,
    /// Typed-dispatch gate posture.
    pub typed_dispatch: TypedDispatchPolicy,
}

