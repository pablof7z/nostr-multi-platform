#[test]
fn runtime_crates_do_not_define_concept_open_doorways() {
    let root = super::workspace_root();
    let mut findings = Vec::new();
    for rel in [
        "crates/nmp-native-runtime/src",
        "crates/nmp-browser-runtime/src",
    ] {
        collect_forbidden_open_fns(&root.join(rel), &mut findings);
    }
    assert!(
        findings.is_empty(),
        "concept read doorways must live in concept crates:\n{}",
        findings.join("\n")
    );
}

/// #2899: every checked-in `concept_reads_<concept>.rs` file in an app-owned
/// facade `src/` tree is GENERATED by `nmp gen concept-reads` and must carry
/// the generator's marker header. This is the doctrine-lint counterpart to the
/// `codegen-drift.yml` `gen concept-reads --check` gate: the CI job proves the
/// bytes match a fresh run; this gate proves nobody has quietly replaced a
/// generated door with a hand-written one that would then drift silently.
#[test]
fn checked_in_concept_read_slices_are_marked_generated() {
    let root = super::workspace_root();
    let apps = root.join("apps");
    let mut files = Vec::new();
    collect_concept_read_slices(&apps, &mut files);

    let mut findings = Vec::new();
    for path in &files {
        let body = fs::read_to_string(path).unwrap();
        // The first line must name the generator (mirrors the emitter header
        // in `crates/nmp-codegen/src/concept_reads/rust.rs`).
        let first = body.lines().next().unwrap_or_default();
        if !first.contains("GENERATED by `nmp gen concept-reads`") {
            findings.push(path.display().to_string());
        }
    }

    assert!(
        findings.is_empty(),
        "#2899: these `concept_reads_*.rs` facade slices are missing the \
         `GENERATED by nmp gen concept-reads` marker — regenerate them with \
         `nmp gen concept-reads --registry <app>/concept-reads.json --platform \
         rust --out <path>` instead of hand-editing (a hand-edited slice would \
         drift silently from the registry):\n{}",
        findings.join("\n")
    );
}

fn collect_concept_read_slices(dir: &Path, out: &mut Vec<std::path::PathBuf>) {
    if !dir.exists() {
        return;
    }
    for entry in fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().and_then(|n| n.to_str()) == Some("target") {
                continue;
            }
            collect_concept_read_slices(&path, out);
            continue;
        }
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        // The generated per-concept slices; exclude the hand-written
        // `*_tests.rs` companions the emitter references but does not own.
        if name.starts_with("concept_reads_")
            && name.ends_with(".rs")
            && !name.ends_with("_tests.rs")
        {
            out.push(path);
        }
    }
}

fn assert_optional_dep(cargo: &str, dep: &str, feature: &str) {
    let line = cargo
        .lines()
        .find(|line| line.trim_start().starts_with(&format!("{dep} = ")))
        .unwrap_or_else(|| panic!("{dep} dependency missing"));
    assert!(
        line.contains("optional = true"),
        "{dep} must stay optional in runtime Cargo.toml"
    );
    let feature_line =
        feature_block(cargo, feature).unwrap_or_else(|| panic!("{feature} feature missing"));
    assert!(
        feature_line.contains(&format!("dep:{dep}")),
        "{feature} feature must own the dep:{dep} edge"
    );
}

fn feature_block(cargo: &str, feature: &str) -> Option<String> {
    let mut lines = cargo.lines();
    while let Some(line) = lines.next() {
        if !line.trim_start().starts_with(&format!("{feature} = ")) {
            continue;
        }
        let mut block = line.to_string();
        while !block.contains(']') {
            let Some(next) = lines.next() else {
                break;
            };
            block.push('\n');
            block.push_str(next);
        }
        return Some(block);
    }
    None
}

fn assert_no_production_dep(cargo: &str, dep: &str) {
    let in_dev_dependency = cargo
        .lines()
        .scan(false, |is_dev, line| {
            let trimmed = line.trim();
            if trimmed.starts_with('[') {
                *is_dev = trimmed == "[dev-dependencies]";
            }
            Some((*is_dev, trimmed.to_string()))
        })
        .any(|(is_dev, line)| !is_dev && line.starts_with(&format!("{dep} = ")));
    assert!(
        !in_dev_dependency,
        "{dep} must not be bundled as a production native-runtime dependency"
    );
}

fn collect_forbidden_open_fns(dir: &Path, findings: &mut Vec<String>) {
    if !dir.exists() {
        return;
    }
    for entry in fs::read_dir(dir).unwrap() {
        let entry = entry.unwrap();
        let path = entry.path();
        if path.is_dir() {
            collect_forbidden_open_fns(&path, findings);
            continue;
        }
        if path.extension().and_then(|ext| ext.to_str()) != Some("rs")
            || path.to_string_lossy().contains("/tests/")
        {
            continue;
        }
        let raw = fs::read_to_string(&path).unwrap();
        for (index, line) in raw.lines().enumerate() {
            let line = line.split("//").next().unwrap_or("").trim();
            if forbidden_open_definition(line) {
                findings.push(format!("{}:{}: {}", path.display(), index + 1, line));
            }
        }
    }
}

fn forbidden_open_definition(line: &str) -> bool {
    let Some(after_fn) = line
        .strip_prefix("pub fn ")
        .or_else(|| line.strip_prefix("fn "))
        .or_else(|| line.strip_prefix("pub(crate) fn "))
    else {
        return false;
    };
    [
        "open_search",
        "close_search",
        "open_group",
        "close_group",
        "open_groups",
        "close_groups",
        "open_reactions",
        "close_reactions",
    ]
    .iter()
    .any(|name| after_fn.starts_with(name))
}
