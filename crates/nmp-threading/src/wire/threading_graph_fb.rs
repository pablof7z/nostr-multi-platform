//! Typed FlatBuffers wire codec for [`crate::projection::ThreadingSnapshot`].
//!
//! The canonical FFI shape is the serde JSON of `ThreadingSnapshot`
//! (`ThreadingProjection::snapshot`). This module adds a **typed FlatBuffers**
//! encoding of the same read model — the typed sidecar (ADR-0037) carried
//! alongside the generic `Value` projection under the same
//! `"nmp.threading.graph"` key. The serde shape stays authoritative; this is
//! the typed payload an `NTHR`-aware host decodes with generated accessors
//! instead of JSON reflection.
//!
//! Raw data only (ADR-0032): pointer ids, coordinates, URIs, and pubkeys are
//! verbatim. No `display::` forwarder runs on the encode path.
//!
//! Honours D6 (no panics): [`decode_threading_snapshot`] returns `Err(String)`
//! on any malformed input; there are no `unwrap`/`expect`/panicking-index
//! operations on the decode path.
//!
//! ## Regenerating the bindings
//!
//! The checked-in bindings in `wire/generated/threading_graph_generated.rs`
//! are produced by `flatc` from `schema/threading_graph.fbs`. Regenerate only
//! with the workspace FlatBuffers pin (`25.12.19`), enforced by
//! `ci/check-flatbuffers-version-pins.sh`. The schema is self-contained, so
//! generate with plain `flatc --rust`:
//!
//! ```sh
//! flatc --rust -o crates/nmp-threading/src/wire/generated \
//!       crates/nmp-threading/schema/threading_graph.fbs
//! ```

// The generated FlatBuffers bindings are intrinsically `unsafe` (every accessor
// reads from a raw `Table`). This single generated module — and only it — opts
// back into `unsafe`. No hand-written code in this file uses `unsafe`.
